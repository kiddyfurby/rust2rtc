pub fn alaw_to_ulaw(val: u8) -> u8 {
    ALAW_TO_ULAW[val as usize]
}

pub fn ulaw_to_alaw(val: u8) -> u8 {
    ULAW_TO_ALAW[val as usize]
}

pub fn transcode_alaw_to_ulaw(data: &mut [u8]) {
    for b in data.iter_mut() {
        *b = ALAW_TO_ULAW[*b as usize];
    }
}

pub fn transcode_ulaw_to_alaw(data: &mut [u8]) {
    for b in data.iter_mut() {
        *b = ULAW_TO_ALAW[*b as usize];
    }
}

/// G.711 RTP Repacker for Camera Backchannels (Reolink, Tapo, etc.)
/// Accumulates incoming audio frames and outputs fixed-size RTP packets
/// with sequential sequence numbers and monotonically increasing timestamps.
pub struct G711Repacker {
    packet_size: usize,
    payload_type: u8,
    ssrc: u32,
    buffer: Vec<u8>,
    sequence_number: u16,
    timestamp: u32,
}

impl G711Repacker {
    /// Create a new repacker.
    /// `packet_size`: Frame size in bytes (e.g. 1024 for Reolink, 160 for 20ms standard)
    /// `payload_type`: 0 for PCMU, 8 for PCMA
    pub fn new(packet_size: usize, payload_type: u8, ssrc: u32) -> Self {
        Self {
            packet_size,
            payload_type,
            ssrc,
            buffer: Vec::with_capacity(packet_size * 2),
            sequence_number: 0,
            timestamp: 0,
        }
    }

    /// Push raw audio payload bytes into the repacker and extract framed RTP packets
    pub fn push_payload(&mut self, payload: &[u8]) -> Vec<Bytes> {
        self.buffer.extend_from_slice(payload);
        let mut packets = Vec::new();

        while self.buffer.len() >= self.packet_size {
            let chunk: Vec<u8> = self.buffer.drain(..self.packet_size).collect();
            let mut rtp_packet = BytesMut::with_capacity(12 + self.packet_size);

            // RTP Header (Marker bit only on first packet of talkspurt)
            let marker = if self.sequence_number == 0 { 0x80 } else { 0x00 };
            rtp_packet.extend_from_slice(&[
                0x80, // Version 2, no padding, no extension, 0 CSRC
                self.payload_type | marker,
            ]);
            rtp_packet.extend_from_slice(&self.sequence_number.to_be_bytes());
            rtp_packet.extend_from_slice(&self.timestamp.to_be_bytes());
            rtp_packet.extend_from_slice(&self.ssrc.to_be_bytes());

            // Payload
            rtp_packet.extend_from_slice(&chunk);

            self.sequence_number = self.sequence_number.wrapping_add(1);
            self.timestamp = self.timestamp.wrapping_add(self.packet_size as u32);

            packets.push(rtp_packet.freeze());
        }

        packets
    }

    /// Reset sequence numbers and buffer
    pub fn reset(&mut self) {
        self.buffer.clear();
        self.sequence_number = 0;
        self.timestamp = 0;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_pcm_transcode() {
        let original_alaw = vec![0x55, 0xaa, 0x00, 0xff];
        let mut buffer = original_alaw.clone();
        transcode_alaw_to_ulaw(&mut buffer);
        assert_ne!(buffer, original_alaw);
        assert_eq!(buffer.len(), original_alaw.len());
        // Verify values are valid G.711 bytes
        for &b in &buffer {
            let _back = ulaw_to_alaw(b);
        }
    }

    #[test]
    fn test_g711_repacker() {
        let mut repacker = G711Repacker::new(1024, 0, 0x12345678);

        // Feed 500 bytes -> no packet yet
        let p1 = repacker.push_payload(&vec![0x7f; 500]);
        assert_eq!(p1.len(), 0);

        // Feed another 600 bytes -> total 1100 -> emits 1 packet of 12 + 1024 = 1036 bytes
        let p2 = repacker.push_payload(&vec![0x7f; 600]);
        assert_eq!(p2.len(), 1);
        assert_eq!(p2[0].len(), 1036);
        assert_eq!(&p2[0][0..2], &[0x80, 0x80]); // Version 2, Marker, PT=0 (PCMU)

        // Check SSRC
        let ssrc = u32::from_be_bytes([p2[0][8], p2[0][9], p2[0][10], p2[0][11]]);
        assert_eq!(ssrc, 0x12345678);

        // Buffer has 76 bytes remaining. Push 948 bytes -> triggers next packet
        let p3 = repacker.push_payload(&vec![0x7f; 948]);
        assert_eq!(p3.len(), 1);

        // Check sequence numbers
        let seq1 = u16::from_be_bytes([p2[0][2], p2[0][3]]);
        let seq2 = u16::from_be_bytes([p3[0][2], p3[0][3]]);
        assert_eq!(seq1, 0);
        assert_eq!(seq2, 1);
    }
}
